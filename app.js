// AUTOMATIC LIVE CUSTOMER VISITOR TRACKER (Admin Analytics)
// ============================================================================
function trackCustomerVisit() {
  try {
    if (typeof window === 'undefined' || typeof document === 'undefined') return;
    
    // Ignore admin panel visits so only customers are counted
    const pathName = window.location.pathname.toLowerCase();
    if (pathName.includes('admin')) return;

    // Persistent visitor unique ID
    let visitorId = localStorage.getItem('ar_visitor_uid');
    if (!visitorId) {
      visitorId = 'cust_' + Date.now().toString(36) + '_' + Math.random().toString(36).substring(2, 7);
      localStorage.setItem('ar_visitor_uid', visitorId);
    }

    // Determine clean page name
    let page = pathName.split('/').pop() || 'index.html';
    if (!page.includes('.')) page = page + '.html';

    // Device detection
    const isMobile = window.innerWidth <= 768 || /Android|iPhone|iPad|iPod|Mobile/i.test(navigator.userAgent);
    const device = isMobile ? 'Mobile' : 'Desktop';

    // Referrer
    let referrer = 'Direct';
    if (document.referrer) {
      try {
        referrer = new URL(document.referrer).hostname || 'Direct';
      } catch (e) {
        referrer = 'Direct';
      }
    }

    const payload = JSON.stringify({
      visitorId,
      page,
      device,
      referrer
    });

    // Send silently without blocking user
    if (navigator.sendBeacon) {
      const blob = new Blob([payload], { type: 'application/json' });
      navigator.sendBeacon('/api/track/visit', blob);
    } else {
      fetch('/api/track/visit', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: payload,
        keepalive: true
      }).catch(() => {});
    }
  } catch (err) {
    // Fail silently so customer experience is never interrupted
  }
}

