function quickAdd(e, id) {
  e.stopPropagation();
  const p = VELOURA_PRODUCTS[id];
  if (!p) return;
  const size = p.sizes ? p.sizes[0] : 'Standard';
  const ex = CURRENT_CART.find(i => i.id === id && i.selectedSize === size);
  if (ex) ex.quantity++;
  else CURRENT_CART.push({ ...p, selectedSize: size, quantity: 1 });
  saveCart(CURRENT_CART);
  updateCartBadges();
  showToast(`✅ Added: "${p.title.slice(0, 40)}…"`);
}

function addToCart(id, size = null, redirect = true) {
  const p = VELOURA_PRODUCTS[id];
  if (!p) return;
  const s = size || (p.sizes ? p.sizes[0] : 'Standard');
  const ex = CURRENT_CART.find(i => i.id === id && i.selectedSize === s);
  if (ex) ex.quantity++;
  else CURRENT_CART.push({ ...p, selectedSize: s, quantity: 1 });
  saveCart(CURRENT_CART);
  updateCartBadges();
  if (redirect) window.location.href = 'cart.html';
}

function updateQuantity(id, size, delta) {
  const item = CURRENT_CART.find(i => i.id === id && i.selectedSize === size);
  if (!item) return;
  item.quantity += delta;
  if (item.quantity <= 0) CURRENT_CART = CURRENT_CART.filter(i => !(i.id === id && i.selectedSize === size));
  saveCart(CURRENT_CART);
  updateCartBadges();
  if (typeof renderCartPage === 'function') renderCartPage();
}

function removeFromCart(id, size) {
  CURRENT_CART = CURRENT_CART.filter(i => !(i.id === id && i.selectedSize === size));
  saveCart(CURRENT_CART);
  updateCartBadges();
  if (typeof renderCartPage === 'function') renderCartPage();
  showToast('Item removed');
}

function updateCartBadges() {
  const total = CURRENT_CART.reduce((s, i) => s + i.quantity, 0);
  document.querySelectorAll('.cart-count-badge, .cart-count-display').forEach(b => b.textContent = total);
}

