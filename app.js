function starHTML(r) {
  const full = Math.floor(r); const half = r % 1 >= 0.5 ? 1 : 0; const empty = 5 - full - half;
  return '★'.repeat(full) + (half ? '½' : '') + '☆'.repeat(empty);
}
function badgeClass(t) {
  return ({bestseller:'badge-bestseller',deal:'badge-deal',new:'badge-new',limited:'badge-limited',viral:'badge-viral',sale:'badge-sale'})[t] || 'badge-new';
}

