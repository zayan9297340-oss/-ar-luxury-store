function handleManualAuth(e) {
  e.preventDefault();
  authErrorMessage = '';

  const emailInput = document.getElementById('authEmailInput');
  const passInput = document.getElementById('authPasswordInput');
  const nameInput = document.getElementById('authNameInput');

  const email = emailInput ? emailInput.value.trim() : '';
  const pass = passInput ? passInput.value.trim() : '';
  const name = nameInput ? nameInput.value.trim() : '';

  // Email format validation
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  if (!email || !emailRegex.test(email)) {
    authErrorMessage = 'Please enter a valid email address (e.g. name@gmail.com).';
    renderAccountModalContent();
    const el = document.getElementById('authEmailInput');
    if (el) { el.classList.add('has-error'); el.focus(); }
    return;
  }

  // Password validation
  if (!pass || pass.length < 6) {
    authErrorMessage = 'Password must be at least 6 characters long.';
    renderAccountModalContent();
    const el = document.getElementById('authPasswordInput');
    if (el) { el.classList.add('has-error'); el.focus(); }
    return;
  }

  const users = getRegisteredUsers();

  if (activeAuthTab === 'signin') {
    // Check if account exists
    const matchedUser = users.find(u => u.email.toLowerCase() === email.toLowerCase());

    if (!matchedUser) {
      authErrorMessage = `No account found with "${email}". Please check your email or click "Create Account" to register.`;
      renderAccountModalContent();
      const el = document.getElementById('authEmailInput');
      if (el) { el.classList.add('has-error'); el.focus(); }
      return;
    }

    if (matchedUser.password !== pass) {
      authErrorMessage = 'Incorrect password. Please verify your password and try again.';
      renderAccountModalContent();
      const el = document.getElementById('authPasswordInput');
      if (el) { el.classList.add('has-error'); el.focus(); }
      return;
    }

    // Success login
    CURRENT_USER = {
      name: matchedUser.name,
      email: matchedUser.email,
      provider: 'email',
      date: new Date().toISOString()
    };
    try {
      localStorage.setItem('ar_auth_user', JSON.stringify(CURRENT_USER));
    } catch (e) {}

    authErrorMessage = '';
    updateAccountHeaderUI();
    renderAccountModalContent();
    showToast(`✅ Welcome back, ${matchedUser.name}!`);

  } else {
    // Create Account mode
    if (!name || name.length < 2) {
      authErrorMessage = 'Please enter your full name (at least 2 characters).';
      renderAccountModalContent();
      const el = document.getElementById('authNameInput');
      if (el) { el.classList.add('has-error'); el.focus(); }
      return;
    }

    const existing = users.find(u => u.email.toLowerCase() === email.toLowerCase());
    if (existing) {
      authErrorMessage = `An account with "${email}" already exists. Please switch to "Sign In".`;
      renderAccountModalContent();
      const el = document.getElementById('authEmailInput');
      if (el) { el.classList.add('has-error'); el.focus(); }
      return;
    }

    // Register new user
    const newUser = { name, email, password: pass };
    saveRegisteredUser(newUser);

    CURRENT_USER = {
      name: name,
      email: email,
      provider: 'email',
      date: new Date().toISOString()
    };
    try {
      localStorage.setItem('ar_auth_user', JSON.stringify(CURRENT_USER));
    } catch (e) {}

    authErrorMessage = '';
    updateAccountHeaderUI();
    renderAccountModalContent();
    showToast(`🎉 Account created! Welcome to AR Store, ${name}.`);
  }
}

