async function syncWithBackend() {
  try {
    const res = await fetch('/api/products');
    const data = await res.json();
    if (data.success && data.products) {
      Object.assign(VELOURA_PRODUCTS, data.products);
      if (typeof window !== 'undefined') window.VELOURA_PRODUCTS = VELOURA_PRODUCTS;
      renderAllSections();
      updateDOMProductPrices(data.products);
    }
  } catch {}
}

function updateDOMProductPrices(prods) {
  if (!prods || typeof document === 'undefined') return;
  document.querySelectorAll('.product-item-card, .product-card').forEach(card => {
    const match = card.innerHTML.match(/(?:openProductModal|addToCart)\(['"]([^'"]+)['"]\)/);
    if (match && match[1] && prods[match[1]]) {
      const p = prods[match[1]];
      const priceEl = card.querySelector('.price-in-pkr, .price, .product-price');
      if (priceEl) priceEl.textContent = `Rs. ${Number(p.price).toLocaleString()}`;
      const imgEl = card.querySelector('img');
      if (imgEl && p.image && !imgEl.src.includes(p.image)) imgEl.src = p.image;
      const titleEl = card.querySelector('.card-p-title, .product-title, h4');
      if (titleEl && p.title) {
        titleEl.textContent = p.title;
        titleEl.title = p.title;
      }
      if (p.badge) {
        const badgeEl = card.querySelector('.badge-tag, .product-badge');
        if (badgeEl) badgeEl.textContent = p.badge;
      }
    }
  });
}

